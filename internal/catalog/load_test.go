// writeTask materialises a task directory from a path -> content map. Building
// the fixtures in code keeps each test case readable next to its expectation.
func writeTask(t *testing.T, root, name string, files map[string]string) string {
	t.Helper()
	dir := filepath.Join(root, name)
	for p, content := range files {
		full := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func validTask(id string) map[string]string {
	return map[string]string{
		"task.yaml":              "id: " + id + "\ntitle: Пример\ntopic: slices\ndifficulty: 2\nestimate_minutes: 10\n",
		"README.md":              "# Условие\n\nСделай что-нибудь.\n",
		"starter/solution.go":    "package solution\n\nfunc Do() {}\n",
		"tests/solution_test.go": "package solution\n\nimport \"testing\"\n\nfunc TestDo(t *testing.T) { Do() }\n",
		"solution/solution.go":   "package solution\n\nfunc Do() {}\n",
	}
}

func TestLoadTask(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := writeTask(t, root, "slices-01", validTask("slices-01"))

	got, err := LoadTask(dir)
	if err != nil {
		t.Fatalf("LoadTask() error = %v", err)
	}
	if got.ID != "slices-01" || got.Title != "Пример" || got.Topic != "slices" {
		t.Errorf("task = %+v", got)
	}
	if got.Difficulty != 2 || got.EstimateMin != 10 {
		t.Errorf("difficulty = %d estimate = %d", got.Difficulty, got.EstimateMin)
	}
	if !got.Race {
		t.Error("Race should default to true")
	}
	if len(got.Starter) != 1 || got.Starter[0].Path != "solution.go" {
		t.Errorf("starter = %+v, want one file at a relative path", got.Starter)
	}
	if len(got.Tests) != 1 || len(got.Solution) != 1 {
		t.Errorf("tests = %d solution = %d, want 1 each", len(got.Tests), len(got.Solution))
	}
	if got.ContentHash == "" {
		t.Error("ContentHash must be set")
	}
}

