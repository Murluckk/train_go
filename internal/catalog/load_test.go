func TestFingerprintChangesWithContent(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeTask(t, root, "a", validTask("a"))

	first, err := Fingerprint(root)
	if err != nil {
		t.Fatal(err)
	}
	same, err := Fingerprint(root)
	if err != nil {
		t.Fatal(err)
	}
	if first != same {
		t.Fatal("fingerprint is not stable across calls")
	}

	p := filepath.Join(root, "a", "README.md")
	if err := os.WriteFile(p, []byte("# Другое условие\n\nтекст\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// Modification time granularity can be coarse; the size change alone must
	// already be enough to move the fingerprint.
	if err := os.Chtimes(p, time.Now(), time.Now().Add(time.Second)); err != nil {
		t.Fatal(err)
	}
	changed, err := Fingerprint(root)
	if err != nil {
		t.Fatal(err)
	}
	if changed == first {
		t.Error("fingerprint did not change after editing a file")
	}
}

func TestContentHashTracksTests(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	files := validTask("a")
	dir := writeTask(t, root, "a", files)
	before, err := LoadTask(dir)
	if err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(filepath.Join(dir, "tests", "solution_test.go"),
		[]byte("package solution\n\nimport \"testing\"\n\nfunc TestDo(t *testing.T) { t.Skip() }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	after, err := LoadTask(dir)
	if err != nil {
		t.Fatal(err)
	}
	if before.ContentHash == after.ContentHash {
		t.Error("changing the tests must change the content hash")
	}
}

func TestValidateUserPath(t *testing.T) {
	t.Parallel()
	tests := []struct {
		path    string
		wantErr string
	}{
		{path: "main.go"},
		{path: "pkg/helper.go"},
		{path: "", wantErr: "empty path"},
		{path: "/etc/passwd.go", wantErr: "must be relative"},
		{path: "../escape.go", wantErr: `must not contain ".." segments`},
		{path: "a/../../escape.go", wantErr: "not a clean path"},
		{path: "./main.go", wantErr: "not a clean path"},
		{path: `pkg\main.go`, wantErr: "forward slashes"},
		{path: "go.mod", wantErr: "owned by the runner"},
		{path: "main_test.go", wantErr: "test files come from the task"},
		{path: "notes.txt", wantErr: "only .go files"},
	}
	for _, tt := range tests {
		t.Run(tt.path, func(t *testing.T) {
			t.Parallel()
			err := ValidateUserPath(tt.path)
			if tt.wantErr == "" {
				if err != nil {
					t.Errorf("ValidateUserPath(%q) = %v, want nil", tt.path, err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
				t.Errorf("ValidateUserPath(%q) = %v, want it to mention %q", tt.path, err, tt.wantErr)
			}
		})
	}
}

