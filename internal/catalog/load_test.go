func TestLoadTaskValidation(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		dirName string
		mutate  func(map[string]string)
		wantErr string
	}{
		{
			name:    "id must match the directory",
			dirName: "renamed",
			wantErr: "does not match directory name",
		},
		{
			name: "difficulty out of range",
			mutate: func(f map[string]string) {
				f["task.yaml"] = strings.Replace(f["task.yaml"], "difficulty: 2", "difficulty: 9", 1)
			},
			wantErr: "difficulty must be 1..3",
		},
		{
			name: "estimate must be positive",
			mutate: func(f map[string]string) {
				f["task.yaml"] = strings.Replace(f["task.yaml"], "estimate_minutes: 10", "estimate_minutes: 0", 1)
			},
			wantErr: "estimate_minutes must be positive",
		},
		{
			name:    "unknown manifest key",
			mutate:  func(f map[string]string) { f["task.yaml"] += "dificulty: 2\n" },
			wantErr: "field dificulty not found",
		},
		{
			name:    "missing readme",
			mutate:  func(f map[string]string) { delete(f, "README.md") },
			wantErr: "read README.md",
		},
		{
			name:    "empty readme",
			mutate:  func(f map[string]string) { f["README.md"] = "  \n" },
			wantErr: "README.md must not be empty",
		},
		{
			name:    "no starter files",
			mutate:  func(f map[string]string) { delete(f, "starter/solution.go") },
			wantErr: "starter/ must contain at least one file",
		},
		{
			name:    "no test files",
			mutate:  func(f map[string]string) { delete(f, "tests/solution_test.go") },
			wantErr: "must contain at least one _test.go",
		},
		{
			name:    "no reference solution",
			mutate:  func(f map[string]string) { delete(f, "solution/solution.go") },
			wantErr: "solution/ must contain the reference implementation",
		},
		{
			name: "starter shadows a test file",
			mutate: func(f map[string]string) {
				f["starter/solution_test.go"] = "package solution\n"
			},
			wantErr: "the editor must not hold test files",
		},
		{
			name: "go.mod checked in",
			mutate: func(f map[string]string) {
				f["starter/go.mod"] = "module x\n"
			},
			wantErr: "generated by the runner",
		},
		{
			name:    "malformed yaml",
			mutate:  func(f map[string]string) { f["task.yaml"] = "id: [unclosed\n" },
			wantErr: "parse task.yaml",
		},
		{
			name:    "id with uppercase",
			dirName: "Slices-01",
			mutate: func(f map[string]string) {
				f["task.yaml"] = strings.Replace(f["task.yaml"], "id: slices-01", "id: Slices-01", 1)
			},
			wantErr: "lowercase letters",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			files := validTask("slices-01")
			if tt.mutate != nil {
				tt.mutate(files)
			}
			dirName := tt.dirName
			if dirName == "" {
				dirName = "slices-01"
			}
			dir := writeTask(t, t.TempDir(), dirName, files)

			_, err := LoadTask(dir)
			if err == nil {
				t.Fatalf("LoadTask() succeeded, want error containing %q", tt.wantErr)
			}
			if !strings.Contains(err.Error(), tt.wantErr) {
				t.Errorf("LoadTask() error = %v, want it to mention %q", err, tt.wantErr)
			}
		})
	}
}

func TestLoadReportsBrokenTasksWithoutFailing(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeTask(t, root, "good-01", validTask("good-01"))
	writeTask(t, root, "broken", map[string]string{"task.yaml": "id: broken\n"})

	snap, err := Load(root)
	if err != nil {
		t.Fatalf("Load() error = %v; one bad task must not fail the scan", err)
	}
	if snap.Len() != 1 {
		t.Errorf("loaded %d tasks, want 1", snap.Len())
	}
	errs := snap.Errors()
	if len(errs) != 1 || errs[0].Dir != "broken" {
		t.Errorf("errors = %+v, want the broken directory reported", errs)
	}
}

